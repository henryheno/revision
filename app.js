const feedContainer = document.getElementById('feed');
const progressText = document.getElementById('progress-text');
const spText = document.getElementById('sous-point-title');
const prevBtn = document.getElementById('btn-prev');
const nextBtn = document.getElementById('btn-next');
const sidebar = document.getElementById('sidebar');
const sidebarOverlay = document.getElementById('sidebar-overlay');
const menuBtn = document.getElementById('menu-btn');
const closeMenuBtn = document.getElementById('close-menu-btn');
const sidebarContent = document.getElementById('sidebar-content');
const repeatBtn = document.getElementById('repeat-btn');

let currentSpeechText = '';

// Met à jour l'en-tête (Dossier, Chapitre, Sous-point)
function updateHeaders(chapitre, sousPoint) {
    document.getElementById('dossier-title').textContent = dossier;
    document.getElementById('chapitre-title').textContent = chapitre || "Chapitre 1";
    spText.textContent = sousPoint || "Généralités";
}

// Fonction pour lire le texte à voix haute (TTS)
function speak(text) {
    if ('speechSynthesis' in window) {
        window.speechSynthesis.cancel(); // Arrête la lecture en cours
        const utterance = new SpeechSynthesisUtterance(text);
        utterance.lang = 'fr-FR';
        window.speechSynthesis.speak(utterance);
    }
}

function renderCurrentQuestion() {
    feedContainer.innerHTML = ''; // Nettoie le conteneur
    
    const item = questionsData[currentIndex];
    if (!item) return;

    updateHeaders(item.chapitre, item.sousPoint);
    
    progressText.textContent = "Question " + (currentIndex + 1) + " / " + questionsData.length;

    const card = document.createElement('div');
    card.className = 'card';
    
    card.innerHTML = "<div class='card-question'>" + item.question + "</div>" +
                     "<div class='card-hint'>Appuyer pour voir la réponse</div>" +
                     "<div class='card-answer'>" + item.answer + "</div>";

    // Interaction pour afficher la réponse
    card.addEventListener('click', () => {
        const isShowing = card.classList.toggle('show-answer');
        if (isShowing) {
            // Nettoyer le HTML pour une lecture propre
            const plainTextAnswer = item.answer.replace(/<[^>]+>/g, ' ').replace(/s+/g, ' ').trim();
            currentSpeechText = plainTextAnswer;
            speak(currentSpeechText);
        } else {
            // Si on referme, on relit la question
            currentSpeechText = item.question;
            speak(currentSpeechText);
        }
    });

    feedContainer.appendChild(card);
    
    // Gérer l'état des boutons
    prevBtn.disabled = currentIndex === 0;
    nextBtn.disabled = currentIndex === questionsData.length - 1;
    
    // Lire la question automatiquement
    currentSpeechText = item.question;
    speak(currentSpeechText);
}

// Répéter l'audio
repeatBtn.addEventListener('click', () => {
    speak(currentSpeechText);
});

// Navigation
prevBtn.addEventListener('click', () => {
    if (currentIndex > 0) {
        currentIndex--;
        renderCurrentQuestion();
    }
});

nextBtn.addEventListener('click', () => {
    if (currentIndex < questionsData.length - 1) {
        currentIndex++;
        renderCurrentQuestion();
    }
});

// Clavier
document.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowRight' || e.key === ' ') {
        nextBtn.click();
    } else if (e.key === 'ArrowLeft') {
        prevBtn.click();
    } else if (e.key === 'Escape') {
        closeMenu();
    }
});

// Menu Latéral
function openMenu() {
    sidebar.classList.add('open');
    sidebarOverlay.classList.add('active');
}

function closeMenu() {
    sidebar.classList.remove('open');
    sidebarOverlay.classList.remove('active');
}

menuBtn.addEventListener('click', openMenu);
closeMenuBtn.addEventListener('click', closeMenu);
sidebarOverlay.addEventListener('click', closeMenu);

function buildNavigationMenu() {
    let lastChapitre = null;
    
    questionsData.forEach((q, index) => {
        // Ajouter le chapitre s'il est nouveau
        if (q.chapitre !== lastChapitre) {
            const chapEl = document.createElement('div');
            chapEl.className = 'menu-chapter';
            chapEl.textContent = q.chapitre;
            chapEl.addEventListener('click', () => {
                currentIndex = index;
                renderCurrentQuestion();
                closeMenu();
            });
            sidebarContent.appendChild(chapEl);
            lastChapitre = q.chapitre;
        }
        
        // On pourrait aussi afficher tous les sous-points, mais pour garder 
        // le menu propre, on ne montre que le 1er sous-point de chaque changement.
        // Comme les questions sont très nombreuses, lier le chapitre principal est prioritaire.
        // Si on veut les sous-points, on vérifie si le sous-point a changé :
    });
    
    // Logique avancée pour les sous-points :
    let currentC = null;
    let currentS = null;
    sidebarContent.innerHTML = ''; // Re-nettoyer pour la logique complète
    
    questionsData.forEach((q, index) => {
        if (q.chapitre !== currentC) {
            const chapEl = document.createElement('div');
            chapEl.className = 'menu-chapter';
            chapEl.textContent = q.chapitre;
            chapEl.addEventListener('click', () => {
                currentIndex = index;
                renderCurrentQuestion();
                closeMenu();
            });
            sidebarContent.appendChild(chapEl);
            currentC = q.chapitre;
            currentS = null; // Reset le sous-point pour le nouveau chapitre
        }
        
        if (q.sousPoint !== currentS) {
            const spEl = document.createElement('div');
            spEl.className = 'menu-souspoint';
            spEl.textContent = q.sousPoint || "Généralités";
            spEl.addEventListener('click', () => {
                currentIndex = index;
                renderCurrentQuestion();
                closeMenu();
            });
            sidebarContent.appendChild(spEl);
            currentS = q.sousPoint;
        }
    });
}

// Initialisation
buildNavigationMenu();
renderCurrentQuestion();
